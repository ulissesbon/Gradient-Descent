/**
 * @brief Lê uma linha de texto da UART2
 * @brief A leitura para ao encontrar '\n' ou atingir o tamanho máximo
 * @brief Ignora '\r'
 * @param buf Ponteiro para o buffer onde a string será armazenada
 * @param maxlen Tamanho máximo do buffer
 * @retval Número de caracteres lidos
 */
int read_line(char *buf, int maxlen)
{
    int pos = 0; // Posição atual no buffer

    // Loop de leitura de caractere
    while (pos < maxlen - 1)
    {
        uint8_t c;
        HAL_UART_Receive(&huart2, &c, 1, HAL_MAX_DELAY);

        if (c == '\n') break;
        if (c == '\r') continue;

        buf[pos++] = c; // Adiciona o caractere válido ao buffer
    }

    buf[pos] = '\0'; // Adiciona o terminador nulo para formar uma string C
    return pos;
}

/* === Função auxiliar para enviar texto formatado pela UART === */
void printTX(const char *fmt, ...) {
    char tx_buff[128];
    va_list args;
    va_start(args, fmt);
    vsnprintf(tx_buff, sizeof(tx_buff), fmt, args);
    va_end(args);
    HAL_UART_Transmit(&huart2, (uint8_t*)tx_buff, strlen(tx_buff), HAL_MAX_DELAY);
}
